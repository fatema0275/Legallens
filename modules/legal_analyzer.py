# ── JSON Sanitization and Safe Parsing ─────────────────────────────────────────

def safe_parse_json(raw_text: str) -> Optional[Union[Dict, List]]:
    """
    Safely parses JSON from an LLM response string.
    Handles code fences (```json ... ```), extraneous conversational preambles,
    and minor formatting anomalies.

    Parameters:
        raw_text (str): Raw string output from the LLM.

    Returns:
        Union[Dict, List] or None: Parsed JSON structure, or None if unparseable.
    """
    if not raw_text or not isinstance(raw_text, str):
        return None

    cleaned = raw_text.strip()

    # 1. Strip markdown code fences if present
    fence_pattern = r"```(?:json)?\s*([\s\S]*?)\s*```"
    match = re.search(fence_pattern, cleaned, re.IGNORECASE)
    if match:
        cleaned = match.group(1).strip()

    # 2. Direct JSON load attempt
    try:
        return json.loads(cleaned)
    except json.JSONDecodeError:
        pass

    # 3. Extract bracketed object {...} or array [...]
    brace_match = re.search(r"(\{[\s\S]*\})", cleaned)
    if brace_match:
        try:
            return json.loads(brace_match.group(1))
        except json.JSONDecodeError:
            pass

    bracket_match = re.search(r"(\[[\s\S]*\])", cleaned)
    if bracket_match:
        try:
            return json.loads(bracket_match.group(1))
        except json.JSONDecodeError:
            pass

    # 4. Attempt trailing comma removal
    try:
        sanitized = re.sub(r",\s*([\}\]])", r"\1", cleaned)
        return json.loads(sanitized)
    except Exception:
        pass

    return None


def normalize_category_name(name: str) -> str:
    """
    Normalizes a clause category name for flexible matching.
    Strips numbering (e.g. '1. ', '1 - ', 'Category 1:'), markdown symbols,
    standardizes '&' to 'and', and removes non-alphanumeric noise.
    """
    if not name or not isinstance(name, str):
        return ""
    text = name.strip().lower()
    # Remove leading numbering like "1.", "1)", "1 -", "category 1:", "clause 1:"
    text = re.sub(r"^(?:category|clause|\d+)?\s*[\d\.\-\)\:]+\s*", "", text).strip()
    # Replace & with and
    text = text.replace("&", " and ")
    # Replace multiple spaces/punctuation with single space
    text = re.sub(r"[^\w\s]", " ", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text


def parse_bool_found(val: Any) -> bool:
    """Robustly parses boolean found flag from LLM output."""
    if isinstance(val, bool):
        return val
    if isinstance(val, (int, float)):
        return val > 0
    if isinstance(val, str):
        v = val.strip().lower()
        if v in ("true", "yes", "1", "found", "identified"):
            return True
        if v in ("false", "no", "0", "not found", "not identified", "none", "null"):
            return False
    return False


def match_clause_category(
    target_category: str,
    extracted_items: List[Dict],
) -> Optional[Dict]:
    """
    Finds a matching clause dictionary from extracted_items for a given target category.
    Supports exact match, normalized match, substring, and token overlap fallbacks.
    """
    norm_target = normalize_category_name(target_category)
    target_tokens = set(norm_target.split())

    best_match = None
    best_score = 0.0

    for item in extracted_items:
        if not isinstance(item, dict):
            continue
        raw_cat = str(item.get("category", "")).strip()
        if not raw_cat:
            continue

        # 1. Exact case-insensitive match
        if raw_cat.lower() == target_category.lower():
            return item

        # 2. Normalized string equality
        norm_item = normalize_category_name(raw_cat)
        if norm_item == norm_target:
            return item

        # 3. Substring match (e.g. "payment" in "payment and compensation")
        if norm_item and (norm_item in norm_target or norm_target in norm_item):
            item_tokens = set(norm_item.split())
            overlap = len(target_tokens & item_tokens)
            if overlap >= 1 and overlap > best_score:
                best_match = item
                best_score = overlap

        # 4. Token overlap matching
        item_tokens = set(norm_item.split())
        overlap = len(target_tokens & item_tokens)
        if overlap >= 2 and overlap > best_score:
            best_match = item
            best_score = overlap

    return best_match



# ── Passage and Context Extraction Helper ────────────────────────────────────

def resolve_document_passages(
    document_data: Any,
    retriever: Optional[Any] = None,
    max_passages: int = 25,
) -> List[Dict]:
    """
    Extracts or resolves a list of chunk passages with source and page metadata.

    Parameters:
        document_data: Extraction dict, chunks list, or raw string.
        retriever: Optional VectorRetriever instance.
        max_passages (int): Maximum passages to include for full-document analysis.

    Returns:
        List[Dict]: List of normalized chunk dictionaries.
    """
    passages: List[Dict] = []

    # Case 1: Chunks directly on retriever
    if retriever is not None and hasattr(retriever, "chunks") and retriever.chunks:
        passages = list(retriever.chunks)

    # Case 2: document_data is a list of chunk dicts
    elif isinstance(document_data, list):
        passages = list(document_data)

    # Case 3: document_data is an extraction_result dict
    elif isinstance(document_data, dict):
        if "chunks" in document_data and document_data["chunks"]:
            passages = list(document_data["chunks"])
        elif "pages" in document_data and document_data["pages"]:
            for p in document_data["pages"]:
                p_text = p.get("text", "").strip()
                if p_text:
                    passages.append(
                        {
                            "chunk_id": f"page_{p.get('page_number', 1)}",
                            "text": p_text,
                            "page_number": p.get("page_number", 1),
                            "source": p.get("source", document_data.get("filename", "document.pdf")),
                        }
                    )

    # Case 4: Plain string
    elif isinstance(document_data, str) and document_data.strip():
        passages = [
            {
                "chunk_id": "chunk_1",
                "text": document_data.strip(),
                "page_number": 1,
                "source": "document.pdf",
            }
        ]

    if len(passages) <= max_passages:
        return passages

    # For larger documents, sample front matter, middle terms, and closing sections
    head_count = max(4, max_passages // 3)
    tail_count = max(4, max_passages // 3)
    mid_count = max_passages - head_count - tail_count

    head = passages[:head_count]
    tail = passages[-tail_count:]
    mid_pool = passages[head_count:-tail_count]

    # Sample middle evenly
    if mid_pool and mid_count > 0:
        step = max(1, len(mid_pool) // mid_count)
        mid = mid_pool[::step][:mid_count]
    else:
        mid = []

    combined = head + mid + tail
    # Deduplicate while preserving order
    seen = set()
    result = []
    for p in combined:
        cid = p.get("chunk_id", p.get("text", "")[:30])
        if cid not in seen:
            seen.add(cid)
            result.append(p)
    return result


def retrieve_clause_passages(
    retriever: Optional[Any],
    fallback_passages: List[Dict],
    categories: List[str],
    top_k_per_category: int = 2,
) -> List[Dict]:
    """
    Retrieves targeted passages for specific clause categories using the FAISS retriever,
    or falls back to sample passages if no retriever is available.
    """
    if retriever is None or not hasattr(retriever, "retrieve"):
        return fallback_passages[:25]

    collected_chunks: Dict[str, Dict] = {}

    for cat in categories:
        query = CLAUSE_SEARCH_QUERIES.get(cat, cat)
        try:
            results = retriever.retrieve(query=query, top_k=top_k_per_category)
            for r in results:
                cid = r.get("chunk_id")
                if cid and cid not in collected_chunks:
                    collected_chunks[cid] = r
        except Exception as exc:
            logger.debug(f"Retriever query for '{cat}' failed: {exc}")

    if collected_chunks:
        # Sort by page number then chunk_id for logical reading order
        return sorted(
            collected_chunks.values(),
            key=lambda x: (x.get("page_number", 1), x.get("chunk_id", "")),
        )

    return fallback_passages[:25]


# ── Core Capability 1: Document Summary ────────────────────────────────────────

def generate_document_summary(
    document_data: Any,
    retriever: Optional[Any] = None,
    llm_config: Optional[Dict[str, Any]] = None,
    client_instance: Optional[object] = None,
) -> Dict[str, Any]:
    """
    Generates a factually grounded executive summary of the legal document.

    Parameters:
        document_data: Document extraction dict, chunk list, or raw string.
        retriever: Optional VectorRetriever instance.
        llm_config: Optional runtime LLM configuration overrides.
        client_instance: Optional injected client instance for unit testing.

    Returns:
        Dict: Structured summary dictionary containing:
            - summary_text (str): Concise 2-4 sentence overview.
            - parties (str): Identified contracting parties.
            - purpose (str): Purpose and scope.
            - obligations (str): Key obligations.
            - key_dates_and_payments (str): Critical milestones, payment terms.
            - termination_and_disputes (str): Termination and dispute terms.
            - source_citations (List[Dict]): Page citations.
            - success (bool): Execution status.
            - error (str or None): Error description if failure occurred.
    """
    passages = resolve_document_passages(document_data, retriever=retriever)
    if not passages:
        return {
            "summary_text": "Not identified in the available text.",
            "parties": "Not identified in the available text.",
            "purpose": "Not identified in the available text.",
            "obligations": "Not identified in the available text.",
            "key_dates_and_payments": "Not identified in the available text.",
            "termination_and_disputes": "Not identified in the available text.",
            "source_citations": [],
            "success": False,
            "error": "No document text or passages provided for summary.",
        }

    citations = extract_citations(passages)
    resolved_config = get_llm_config(override_config=llm_config)
    api_key = resolved_config.get("api_key", "")

    if client_instance is None and not is_valid_api_key(api_key):
        return {
            "summary_text": "LLM API Key Not Configured: Set LLM_API_KEY in your .env file to generate document summary.",
            "parties": "Not identified in the available text.",
            "purpose": "Not identified in the available text.",
            "obligations": "Not identified in the available text.",
            "key_dates_and_payments": "Not identified in the available text.",
            "termination_and_disputes": "Not identified in the available text.",
            "source_citations": citations,
            "success": False,
            "error": "Missing or placeholder LLM API key.",
        }

    messages = build_summary_messages(passages)

    try:
        raw_output = call_llm(messages, resolved_config, client_instance=client_instance)
        parsed = safe_parse_json(raw_output)

        if isinstance(parsed, dict):
            return {
                "summary_text": parsed.get("summary_text", "").strip() or "Not identified in the available text.",
                "parties": parsed.get("parties", "").strip() or "Not identified in the available text.",
                "purpose": parsed.get("purpose", "").strip() or "Not identified in the available text.",
                "obligations": parsed.get("obligations", "").strip() or "Not identified in the available text.",
                "key_dates_and_payments": (
                    parsed.get("key_dates_and_payments", "").strip() or "Not identified in the available text."
                ),
                "termination_and_disputes": (
                    parsed.get("termination_and_disputes", "").strip() or "Not identified in the available text."
                ),
                "source_citations": citations,
                "success": True,
                "error": None,
            }

        # Fallback if model returned plain string instead of JSON
        plain_summary = raw_output.strip() if raw_output else "Not identified in the available text."
        return {
            "summary_text": plain_summary,
            "parties": "Not identified in the available text.",
            "purpose": "Not identified in the available text.",
            "obligations": "Not identified in the available text.",
            "key_dates_and_payments": "Not identified in the available text.",
            "termination_and_disputes": "Not identified in the available text.",
            "source_citations": citations,
            "success": True,
            "error": "Model response was not in JSON format; converted to plain summary.",
        }

    except Exception as exc:
        logger.error(f"Module 5 summary generation failed: {exc}")
        return {
            "summary_text": f"Error generating document summary: {exc}",
            "parties": "Not identified in the available text.",
            "purpose": "Not identified in the available text.",
            "obligations": "Not identified in the available text.",
            "key_dates_and_payments": "Not identified in the available text.",
            "termination_and_disputes": "Not identified in the available text.",
            "source_citations": citations,
            "success": False,
            "error": str(exc),
        }


# ── Core Capability 2: Important Clause Identification ─────────────────────────

def identify_important_clauses(
    document_data: Any,
    retriever: Optional[Any] = None,
    categories: Optional[List[str]] = None,
    llm_config: Optional[Dict[str, Any]] = None,
    client_instance: Optional[object] = None,
) -> Dict[str, Any]:
    """
    Identifies and evaluates standard legal clauses across the document.

    Parameters:
        document_data: Document extraction dict, chunk list, or raw string.
        retriever: Optional VectorRetriever instance.
        categories: Optional list of clause categories to inspect.
        llm_config: Optional runtime LLM configuration overrides.
        client_instance: Optional injected client instance for unit testing.

    Returns:
        Dict: Structured result dictionary containing:
            - clauses (List[Dict]): List of clause objects with found status, explanation,
              evidence quote, and page numbers.
            - total_found (int): Number of identified clauses.
            - total_categories (int): Number of requested categories.
            - success (bool): Execution status.
            - error (str or None): Error message if any occurred.
    """
    target_categories = categories or STANDARD_CLAUSE_CATEGORIES
    all_passages = resolve_document_passages(document_data, retriever=retriever)

    # Empty document guard
    if not all_passages:
        empty_clauses = [
            {
                "category": cat,
                "found": False,
                "explanation": "Not identified in the available text.",
                "evidence": "Not identified in the available text.",
                "page_numbers": [],
                "source": "document.pdf",
            }
            for cat in target_categories
        ]
        return {
            "clauses": empty_clauses,
            "total_found": 0,
            "total_categories": len(target_categories),
            "success": False,
            "error": "No document passages available to evaluate clauses.",
        }

    # Retrieve targeted passages
    clause_passages = retrieve_clause_passages(
        retriever=retriever,
        fallback_passages=all_passages,
        categories=target_categories,
        top_k_per_category=2,
    )

    primary_source = clause_passages[0].get("source", "document.pdf") if clause_passages else "document.pdf"
    resolved_config = get_llm_config(override_config=llm_config)
    api_key = resolved_config.get("api_key", "")

    if client_instance is None and not is_valid_api_key(api_key):
        unauth_clauses = [
            {
                "category": cat,
                "found": False,
                "explanation": "LLM API Key Not Configured: Set LLM_API_KEY in .env to identify clauses.",
                "evidence": "Not identified in the available text.",
                "page_numbers": [],
                "source": primary_source,
            }
            for cat in target_categories
        ]
        return {
            "clauses": unauth_clauses,
            "total_found": 0,
            "total_categories": len(target_categories),
            "success": False,
            "error": "Missing or placeholder LLM API key.",
        }

    messages = build_clauses_messages(clause_passages, categories=target_categories)

    try:
        raw_output = call_llm(messages, resolved_config, client_instance=client_instance)
        parsed = safe_parse_json(raw_output)

        extracted_list: List[Dict] = []
        if isinstance(parsed, dict) and "clauses" in parsed and isinstance(parsed["clauses"], list):
            extracted_list = parsed["clauses"]
        elif isinstance(parsed, list):
            extracted_list = parsed

        normalized_clauses: List[Dict] = []
        found_counter = 0

        for cat in target_categories:
            match = match_clause_category(cat, extracted_list)
            if match:
                is_found = parse_bool_found(match.get("found", False))
                # Normalize page numbers to list of ints
                raw_pages = match.get("page_numbers", [])
                page_nums = []
                if isinstance(raw_pages, list):
                    for p in raw_pages:
                        try:
                            page_nums.append(int(p))
                        except (ValueError, TypeError):
                            pass
                elif isinstance(raw_pages, (int, str)):
                    try:
                        page_nums.append(int(raw_pages))
                    except (ValueError, TypeError):
                        pass

                clause_entry = {
                    "category": cat,
                    "found": is_found,
                    "explanation": match.get("explanation", "").strip() or "Not identified in the available text.",
                    "evidence": match.get("evidence", "").strip() or "Not identified in the available text.",
                    "page_numbers": sorted(list(set(page_nums))),
                    "source": match.get("source", primary_source),
                }
                if is_found and clause_entry["explanation"] != "Not identified in the available text.":
                    found_counter += 1
                normalized_clauses.append(clause_entry)
            else:
                # Category was not identified by model
                normalized_clauses.append(
                    {
                        "category": cat,
                        "found": False,
                        "explanation": "Not identified in the available text.",
                        "evidence": "Not identified in the available text.",
                        "page_numbers": [],
                        "source": primary_source,
                    }
                )

        return {
            "clauses": normalized_clauses,
            "total_found": found_counter,
            "total_categories": len(target_categories),
            "success": True,
            "error": None,
        }

    except Exception as exc:
        logger.error(f"Module 5 clause identification failed: {exc}")
        fallback_clauses = [
            {
                "category": cat,
                "found": False,
                "explanation": f"Error during clause identification: {exc}",
                "evidence": "Not identified in the available text.",
                "page_numbers": [],
                "source": primary_source,
            }
            for cat in target_categories
        ]
        return {
            "clauses": fallback_clauses,
            "total_found": 0,
            "total_categories": len(target_categories),
            "success": False,
            "error": str(exc),
        }


# ── Core Capability 3: Potential Risk Identification ───────────────────────────

def identify_potential_risks(
    document_data: Any,
    retriever: Optional[Any] = None,
    llm_config: Optional[Dict[str, Any]] = None,
    client_instance: Optional[object] = None,
) -> Dict[str, Any]:
    """
    Audits document clauses for potential legal risks, one-sided provisions, and ambiguities.

    Parameters:
        document_data: Document extraction dict, chunk list, or raw string.
        retriever: Optional VectorRetriever instance.
        llm_config: Optional runtime LLM configuration overrides.
        client_instance: Optional injected client instance for unit testing.

    Returns:
        Dict: Structured result dictionary containing:
            - risks (List[Dict]): List of risk flags with category, severity, explanation,
              evidence quote, page numbers, and clarification question.
            - total_risks (int): Count of identified risks.
            - high_severity_count (int): Count of High severity risks.
            - medium_severity_count (int): Count of Medium severity risks.
            - low_severity_count (int): Count of Low severity risks.
            - success (bool): Execution status.
            - error (str or None): Error message if any occurred.
    """
    all_passages = resolve_document_passages(document_data, retriever=retriever)
    if not all_passages:
        return {
            "risks": [],
            "total_risks": 0,
            "high_severity_count": 0,
            "medium_severity_count": 0,
            "low_severity_count": 0,
            "success": False,
            "error": "No document passages available to evaluate legal risks.",
        }

    # Focus retrieval on high-liability and risk-prone covenants
    risk_query_categories = [
        "Liability and indemnification",
        "Payment and compensation",
        "Termination and notice periods",
        "Automatic renewal",
        "Penalties and damages",
        "Intellectual property and ownership",
        "Governing law and dispute resolution",
        "Confidentiality",
    ]
    risk_passages = retrieve_clause_passages(
        retriever=retriever,
        fallback_passages=all_passages,
        categories=risk_query_categories,
        top_k_per_category=3,
    )

    primary_source = risk_passages[0].get("source", "document.pdf") if risk_passages else "document.pdf"
    resolved_config = get_llm_config(override_config=llm_config)
    api_key = resolved_config.get("api_key", "")

    if client_instance is None and not is_valid_api_key(api_key):
        return {
            "risks": [],
            "total_risks": 0,
            "high_severity_count": 0,
            "medium_severity_count": 0,
            "low_severity_count": 0,
            "success": False,
            "error": "Missing or placeholder LLM API key.",
        }

    messages = build_risks_messages(risk_passages)

    try:
        raw_output = call_llm(messages, resolved_config, client_instance=client_instance)
        parsed = safe_parse_json(raw_output)

        raw_risks: List[Dict] = []
        if isinstance(parsed, dict) and "risks" in parsed and isinstance(parsed["risks"], list):
            raw_risks = parsed["risks"]
        elif isinstance(parsed, list):
            raw_risks = parsed

        normalized_risks: List[Dict] = []
        high_cnt = 0
        med_cnt = 0
        low_cnt = 0

        VALID_SEVERITIES = {"Low", "Medium", "High"}

        for item in raw_risks:
            if not isinstance(item, dict):
                continue

            raw_sev = str(item.get("severity", "Medium")).strip().capitalize()
            severity = raw_sev if raw_sev in VALID_SEVERITIES else "Medium"

            if severity == "High":
                high_cnt += 1
            elif severity == "Medium":
                med_cnt += 1
            else:
                low_cnt += 1

            # Normalize pages
            raw_pages = item.get("page_numbers", [])
            page_nums = []
            if isinstance(raw_pages, list):
                for p in raw_pages:
                    try:
                        page_nums.append(int(p))
                    except (ValueError, TypeError):
                        pass
            elif isinstance(raw_pages, (int, str)):
                try:
                    page_nums.append(int(raw_pages))
                except (ValueError, TypeError):
                    pass

            risk_entry = {
                "risk_category": item.get("risk_category", "Contractual Term Risk").strip(),
                "severity": severity,
                "explanation": item.get("explanation", "").strip() or "Deserves review for clarity and balanced terms.",
                "evidence": item.get("evidence", "").strip() or "Not identified in the available text.",
                "page_numbers": sorted(list(set(page_nums))),
                "clarification_question": (
                    item.get("clarification_question", "").strip()
                    or "Would the counterparty be amenable to clarifying or balancing this term?"
                ),
                "source": item.get("source", primary_source),
            }
            normalized_risks.append(risk_entry)

        return {
            "risks": normalized_risks,
            "total_risks": len(normalized_risks),
            "high_severity_count": high_cnt,
            "medium_severity_count": med_cnt,
            "low_severity_count": low_cnt,
            "success": True,
            "error": None,
        }

    except Exception as exc:
        logger.error(f"Module 5 risk identification failed: {exc}")
        return {
            "risks": [],
            "total_risks": 0,
            "high_severity_count": 0,
            "medium_severity_count": 0,
            "low_severity_count": 0,
            "success": False,
            "error": str(exc),
        }


# ── Full Legal Document Analysis Orchestration ─────────────────────────────────

def analyze_legal_document(
    document_data: Any,
    retriever: Optional[Any] = None,
    llm_config: Optional[Dict[str, Any]] = None,
    client_instance: Optional[object] = None,
) -> Dict[str, Any]:
    """
    Orchestrates complete Module 5 Legal Document Analysis:
    1. Executive Document Summary
    2. Important Clause Identification (9 categories)
    3. Potential Risk Identification & Severity Rating

    Parameters:
        document_data: Document extraction dict, chunk list, or raw text.
        retriever: Optional VectorRetriever instance.
        llm_config: Optional runtime LLM configuration overrides.
        client_instance: Optional injected client instance for unit testing.

    Returns:
        Dict: Comprehensive analysis bundle containing:
            - summary (Dict): Document summary details.
            - clauses (List[Dict]): Identified clauses across standard categories.
            - risks (List[Dict]): Identified risks with severity and questions.
            - total_clauses_found (int): Count of identified clauses.
            - total_risks_found (int): Count of flagged risks.
            - high_severity_risks (int): Count of High severity risks.
            - disclaimer (str): Mandatory non-legal-advice disclaimer.
            - success (bool): Overall execution status.
            - error (str or None): Error message if any phase failed.
    """
    # 1. Summary
    summary_res = generate_document_summary(
        document_data=document_data,
        retriever=retriever,
        llm_config=llm_config,
        client_instance=client_instance,
    )

    # 2. Clauses
    clauses_res = identify_important_clauses(
        document_data=document_data,
        retriever=retriever,
        llm_config=llm_config,
        client_instance=client_instance,
    )

    # 3. Risks
    risks_res = identify_potential_risks(
        document_data=document_data,
        retriever=retriever,
        llm_config=llm_config,
        client_instance=client_instance,
    )

    overall_success = summary_res["success"] or clauses_res["success"] or risks_res["success"]
    error_parts = [r["error"] for r in (summary_res, clauses_res, risks_res) if r.get("error")]
    combined_error = "; ".join(error_parts) if error_parts else None

    return {
        "summary": summary_res,
        "clauses": clauses_res.get("clauses", []),
        "risks": risks_res.get("risks", []),
        "total_clauses_found": clauses_res.get("total_found", 0),
        "total_risks_found": risks_res.get("total_risks", 0),
        "high_severity_risks": risks_res.get("high_severity_count", 0),
        "disclaimer": LEGAL_DISCLAIMER,
        "success": overall_success,
        "error": combined_error,
    }
