"""
utils/report_generator.py
Module 6: Consolidated Results & Report Export

Generates downloadable, factually grounded legal analysis reports in Markdown,
Plain Text, and JSON formats based strictly on extracted text and analysis results.

Includes:
- Document filename, generation timestamp, and text statistics.
- Grounded executive document summary with page citations.
- 9 standard legal clause categories with status, explanations, and verbatim quotes.
- Potential risk audit with severity rankings, explanations, quotes, and questions.
- Prominent mandatory non-legal-advice disclaimer.
- Complete privacy protection: never outputs API keys or environment secrets.
"""

import json
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional


def format_page_numbers(page_numbers: Optional[List[int]]) -> str:
    """Formats a list of integer page numbers into a clean reference string."""
    if not page_numbers:
        return "N/A"
    clean_pages = sorted(list(set(p for p in page_numbers if isinstance(p, int) or str(p).isdigit())))
    if not clean_pages:
        return "N/A"
    if len(clean_pages) == 1:
        return f"Page {clean_pages[0]}"
    return "Pages " + ", ".join(str(p) for p in clean_pages)


def generate_markdown_report(
    filename: str,
    extraction_result: Optional[Dict[str, Any]] = None,
    analysis_result: Optional[Dict[str, Any]] = None,
    timestamp: Optional[str] = None,
) -> str:
    """
    Generates a comprehensive, cleanly structured Markdown legal analysis report.

    Parameters:
        filename (str): Name of the analyzed PDF document.
        extraction_result (Optional[Dict]): Extraction metrics from Module 1.
        analysis_result (Optional[Dict]): Analysis bundle from Module 5.
        timestamp (Optional[str]): ISO or formatted date string (defaults to current UTC).

    Returns:
        str: Complete Markdown report text.
    """
    report_time = timestamp or datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    lines: List[str] = []

    # Title & Header
    lines.append(f"# LegalLens — Document Analysis Report")
    lines.append("")
    lines.append(f"**Document Filename:** `{filename or 'document.pdf'}`  ")
    lines.append(f"**Analysis Generated:** {report_time}  ")

    # Document Statistics (from Module 1)
    if extraction_result and extraction_result.get("success"):
        pages = extraction_result.get("total_pages", "N/A")
        words = extraction_result.get("word_count", 0)
        chars = extraction_result.get("char_count", 0)
        lines.append(f"**Document Metrics:** {pages} pages | {words:,} words | {chars:,} characters  ")
    lines.append("")
    lines.append("---")
    lines.append("")

    # Mandatory Legal Disclaimer
    disclaimer = (
        analysis_result.get("disclaimer")
        if analysis_result and analysis_result.get("disclaimer")
        else (
            "This analysis is generated by an automated AI assistant for document intelligence "
            "and preliminary informational review. It does not constitute formal legal advice "
            "or a definitive enforceability ruling."
        )
    )
    lines.append("> **IMPORTANT LEGAL NOTICE**  ")
    lines.append(f"> {disclaimer}")
    lines.append("")
    lines.append("---")
    lines.append("")

    # If no analysis has been performed yet
    if not analysis_result:
        lines.append("## Executive Summary")
        lines.append("")
        lines.append("*Legal document analysis has not been executed for this document yet.*")
        lines.append("")
        lines.append("## Important Clauses")
        lines.append("")
        lines.append("*Clause identification has not been executed for this document yet.*")
        lines.append("")
        lines.append("## Potential Risk Flags")
        lines.append("")
        lines.append("*Risk audit has not been executed for this document yet.*")
        lines.append("")
        return "\n".join(lines)

    summary_data = analysis_result.get("summary") or {}
    clauses_data = analysis_result.get("clauses") or []
    risks_data = analysis_result.get("risks") or []
    risks_evaluated = bool(analysis_result.get("risks_evaluated", False))

    # SECTION 1: EXECUTIVE SUMMARY
    lines.append("## 1. Executive Document Summary")
    lines.append("")

    if not summary_data or not summary_data.get("summary_text"):
        lines.append("*Executive summary has not been generated yet.*")
        lines.append("")
    else:
        overview_text = summary_data.get("summary_text", "Not identified in the available text.")
        lines.append(f"**Overview:**  \n{overview_text}")
        lines.append("")

        dimensions = [
            ("Parties Involved", summary_data.get("parties")),
            ("Document Purpose", summary_data.get("purpose")),
            ("Main Obligations", summary_data.get("obligations")),
            ("Important Dates & Payments", summary_data.get("key_dates_and_payments")),
            ("Termination & Disputes", summary_data.get("termination_and_disputes")),
        ]

        lines.append("### Key Transactional Dimensions")
        for label, val in dimensions:
            display_val = val if val and val.strip() else "Not identified in the available text."
            lines.append(f"- **{label}:** {display_val}")
        lines.append("")

        citations = summary_data.get("source_citations", [])
        if citations:
            cite_pages = [str(c.get("page_number", "?")) for c in citations if isinstance(c, dict)]
            if cite_pages:
                lines.append(f"**Source Pages Cited:** {', '.join(cite_pages)}")
                lines.append("")

    lines.append("---")
    lines.append("")

    # SECTION 2: IMPORTANT CLAUSE INSPECTION
    lines.append("## 2. Important Clause Inspection (9 Categories)")
    lines.append("")

    if not clauses_data:
        lines.append("*Clause category identification has not been generated yet.*")
        lines.append("")
    else:
        total_found = analysis_result.get("total_clauses_found", 0)
        lines.append(f"**Identified Categories:** {total_found} of {len(clauses_data)} present in document text.")
        lines.append("")

        for idx, clause in enumerate(clauses_data, start=1):
            category = clause.get("category", f"Category {idx}")
            is_found = bool(clause.get("found", False))
            status_badge = "✅ Identified" if is_found else "⚪ Not Identified in text"
            explanation = clause.get("explanation", "Not identified in the available text.")
            evidence = clause.get("evidence")
            pages_str = format_page_numbers(clause.get("page_numbers"))

            lines.append(f"### 2.{idx} {category} — {status_badge}")
            lines.append(f"- **Status:** {status_badge}")
            lines.append(f"- **Location:** {pages_str}")
            lines.append(f"- **Explanation:** {explanation}")

            if is_found and evidence and evidence != "Not identified in the available text.":
                lines.append(f"- **Verbatim Quote:**")
                lines.append(f"  > \"{evidence}\"")
            lines.append("")

    lines.append("---")
    lines.append("")

    # SECTION 3: POTENTIAL RISK AUDIT
    lines.append("## 3. Potential Risk & Liability Audit")
    lines.append("")

    if not risks_evaluated and not risks_data:
        lines.append("*Potential risk audit has not been generated yet.*")
        lines.append("")
    elif not risks_data:
        lines.append("✅ **No specific high-exposure contractual risks flagged during audit.**")
        lines.append("")
    else:
        high_cnt = analysis_result.get("high_severity_risks", 0)
        total_risks = len(risks_data)
        lines.append(f"**Total Risks Flagged:** {total_risks} (High Severity: {high_cnt})")
        lines.append("")

        for idx, risk in enumerate(risks_data, start=1):
            category = risk.get("risk_category", "Contractual Term Risk")
            severity = risk.get("severity", "Medium")
            explanation = risk.get("explanation", "Deserves review for clarity.")
            evidence = risk.get("evidence")
            pages_str = format_page_numbers(risk.get("page_numbers"))
            question = risk.get("clarification_question")

            lines.append(f"### 3.{idx} [{severity.upper()}] {category}")
            lines.append(f"- **Severity:** {severity}")
            lines.append(f"- **Location:** {pages_str}")
            lines.append(f"- **Analysis:** {explanation}")

            if evidence and evidence != "Not identified in the available text.":
                lines.append(f"- **Supporting Evidence:**")
                lines.append(f"  > \"{evidence}\"")

            if question:
                lines.append(f"- **Recommended Clarification Question:**")
                lines.append(f"  *\"{question}\"*")
            lines.append("")

    lines.append("---")
    lines.append("*Report generated automatically by LegalLens Document Intelligence.*")
    return "\n".join(lines)


def generate_text_report(
    filename: str,
    extraction_result: Optional[Dict[str, Any]] = None,
    analysis_result: Optional[Dict[str, Any]] = None,
    timestamp: Optional[str] = None,
) -> str:
    """
    Generates a clean plain-text (.txt) legal analysis report suitable for raw viewing.
    """
    report_time = timestamp or datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    sep_major = "=" * 78
    sep_minor = "-" * 78

    lines: List[str] = []
    lines.append(sep_major)
    lines.append("LEGALLENS - LEGAL DOCUMENT ANALYSIS REPORT".center(78))
    lines.append(sep_major)
    lines.append(f"Document Filename : {filename or 'document.pdf'}")
    lines.append(f"Analysis Generated: {report_time}")

    if extraction_result and extraction_result.get("success"):
        pages = extraction_result.get("total_pages", "N/A")
        words = extraction_result.get("word_count", 0)
        chars = extraction_result.get("char_count", 0)
        lines.append(f"Document Metrics  : {pages} pages | {words:,} words | {chars:,} characters")

    lines.append(sep_minor)
    lines.append("IMPORTANT LEGAL NOTICE:")
    lines.append(
        "This analysis is generated by an automated AI assistant for document intelligence\n"
        "and preliminary informational review. It does not constitute formal legal advice\n"
        "or a definitive enforceability ruling."
    )
    lines.append(sep_major)
    lines.append("")

    if not analysis_result:
        lines.append("Legal document analysis has not been executed for this document yet.")
        lines.append(sep_major)
        return "\n".join(lines)

    summary_data = analysis_result.get("summary") or {}
    clauses_data = analysis_result.get("clauses") or []
    risks_data = analysis_result.get("risks") or []
    risks_evaluated = bool(analysis_result.get("risks_evaluated", False))

    # SECTION 1: SUMMARY
    lines.append("1. EXECUTIVE DOCUMENT SUMMARY")
    lines.append(sep_minor)
    if not summary_data or not summary_data.get("summary_text"):
        lines.append("Executive summary has not been generated yet.\n")
    else:
        lines.append(f"Overview:\n{summary_data.get('summary_text', 'Not identified in the available text.')}\n")
        lines.append(f"Parties Involved           : {summary_data.get('parties', 'Not identified')}")
        lines.append(f"Document Purpose           : {summary_data.get('purpose', 'Not identified')}")
        lines.append(f"Main Obligations           : {summary_data.get('obligations', 'Not identified')}")
        lines.append(f"Important Dates & Payments : {summary_data.get('key_dates_and_payments', 'Not identified')}")
        lines.append(f"Termination & Disputes     : {summary_data.get('termination_and_disputes', 'Not identified')}\n")

    # SECTION 2: CLAUSES
    lines.append("2. IMPORTANT CLAUSE INSPECTION")
    lines.append(sep_minor)
    if not clauses_data:
        lines.append("Clause category identification has not been generated yet.\n")
    else:
        total_found = analysis_result.get("total_clauses_found", 0)
        lines.append(f"Identified Categories: {total_found} of {len(clauses_data)} present in document text.\n")
        for idx, clause in enumerate(clauses_data, start=1):
            category = clause.get("category", f"Category {idx}")
            is_found = bool(clause.get("found", False))
            status_str = "IDENTIFIED" if is_found else "NOT IDENTIFIED IN TEXT"
            pages_str = format_page_numbers(clause.get("page_numbers"))
            lines.append(f"[{idx}] {category} [{status_str}]")
            lines.append(f"    Location   : {pages_str}")
            lines.append(f"    Explanation: {clause.get('explanation', 'Not identified in text.')}")
            if is_found and clause.get("evidence") and clause.get("evidence") != "Not identified in the available text.":
                lines.append(f"    Evidence   : \"{clause.get('evidence')}\"")
            lines.append("")

    # SECTION 3: RISKS
    lines.append("3. POTENTIAL RISK & LIABILITY AUDIT")
    lines.append(sep_minor)
    if not risks_evaluated and not risks_data:
        lines.append("Potential risk audit has not been generated yet.\n")
    elif not risks_data:
        lines.append("No specific high-exposure contractual risks flagged during audit.\n")
    else:
        lines.append(f"Flagged Risks: {len(risks_data)} (High Severity: {analysis_result.get('high_severity_risks', 0)})\n")
        for idx, risk in enumerate(risks_data, start=1):
            category = risk.get("risk_category", "Contractual Term Risk")
            severity = risk.get("severity", "Medium")
            pages_str = format_page_numbers(risk.get("page_numbers"))
            lines.append(f"[{idx}] {category} [SEVERITY: {severity.upper()}]")
            lines.append(f"    Location   : {pages_str}")
            lines.append(f"    Analysis   : {risk.get('explanation', '')}")
            if risk.get("evidence") and risk.get("evidence") != "Not identified in the available text.":
                lines.append(f"    Evidence   : \"{risk.get('evidence')}\"")
            if risk.get("clarification_question"):
                lines.append(f"    Question   : \"{risk.get('clarification_question')}\"")
            lines.append("")

    lines.append(sep_major)
    lines.append("END OF REPORT".center(78))
    lines.append(sep_major)
    return "\n".join(lines)


def generate_json_report(
    filename: str,
    extraction_result: Optional[Dict[str, Any]] = None,
    analysis_result: Optional[Dict[str, Any]] = None,
    timestamp: Optional[str] = None,
) -> str:
    """
    Generates a sanitized JSON export of the complete analysis report.
    Guarantees no internal secrets or environment credentials are included.
    """
    report_time = timestamp or datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    doc_metrics = {}
    if extraction_result and extraction_result.get("success"):
        doc_metrics = {
            "total_pages": extraction_result.get("total_pages", 0),
            "word_count": extraction_result.get("word_count", 0),
            "char_count": extraction_result.get("char_count", 0),
        }

    export_obj = {
        "metadata": {
            "report_title": "LegalLens Document Analysis Report",
            "document_filename": filename or "document.pdf",
            "generated_at": report_time,
            "document_metrics": doc_metrics,
            "disclaimer": (
                analysis_result.get("disclaimer")
                if analysis_result and analysis_result.get("disclaimer")
                else (
                    "This analysis is generated by an automated AI assistant for document intelligence "
                    "and preliminary informational review. It does not constitute formal legal advice."
                )
            ),
        },
        "analysis": {
            "summary": analysis_result.get("summary", {}) if analysis_result else None,
            "clauses": analysis_result.get("clauses", []) if analysis_result else [],
            "risks": analysis_result.get("risks", []) if analysis_result else [],
            "total_clauses_found": analysis_result.get("total_clauses_found", 0) if analysis_result else 0,
            "total_risks_found": analysis_result.get("total_risks_found", 0) if analysis_result else 0,
            "high_severity_risks": analysis_result.get("high_severity_risks", 0) if analysis_result else 0,
        },
    }
    return json.dumps(export_obj, indent=2)


def generate_analysis_report(
    filename: str,
    extraction_result: Optional[Dict[str, Any]] = None,
    analysis_result: Optional[Dict[str, Any]] = None,
    export_format: str = "markdown",
    timestamp: Optional[str] = None,
) -> str:
    """
    Main dispatch helper for report generation.

    Parameters:
        filename (str): Name of the analyzed file.
        extraction_result: Extracted document metrics.
        analysis_result: Analysis bundle.
        export_format (str): 'markdown' | 'text' | 'json'
        timestamp (Optional[str]): Explicit timestamp for testing determinism.

    Returns:
        str: Serialized report content.
    """
    fmt = export_format.lower().strip()
    if fmt in ("txt", "text", "plain"):
        return generate_text_report(
            filename=filename,
            extraction_result=extraction_result,
            analysis_result=analysis_result,
            timestamp=timestamp,
        )
    elif fmt == "json":
        return generate_json_report(
            filename=filename,
            extraction_result=extraction_result,
            analysis_result=analysis_result,
            timestamp=timestamp,
        )
    # Default to markdown
    return generate_markdown_report(
        filename=filename,
        extraction_result=extraction_result,
        analysis_result=analysis_result,
        timestamp=timestamp,
    )
